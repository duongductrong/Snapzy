//
//  AutomationClipboardWatcher.swift
//  Snapzy
//
//  "When an image is copied": macOS has no clipboard notification, so a
//  timer reads only `NSPasteboard.changeCount` (an integer, no content) once a
//  second while some automation uses the trigger. The content is looked at
//  only after the count changed, and skipped when Snapzy wrote it, when the
//  writer marked it concealed / transient (password managers) or when it
//  holds no image (text, a non-image file from Finder).
//

import AppKit
import UniformTypeIdentifiers

/// What the watcher reads; a seam so the decision logic is testable.
@MainActor
protocol AutomationPasteboardReading: AnyObject {
  var changeCount: Int { get }
  var types: [NSPasteboard.PasteboardType]? { get }
  func fileURLs() -> [URL]
}

extension NSPasteboard: AutomationPasteboardReading {
  func fileURLs() -> [URL] {
    readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
  }
}

@MainActor
final class AutomationClipboardWatcher {
  /// Explicit and nonisolated: the synthesized main-actor deinit hops through the
  /// back-deployed swift_task_deinitOnExecutor, which aborts on macOS 13-15 (#668).
  nonisolated deinit {}

  /// nspasteboard.org markers: never act on these.
  static let privateTypes: Set<NSPasteboard.PasteboardType> = [
    NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
    NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
    NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
  ]

  static let imageDataTypes: Set<NSPasteboard.PasteboardType> = [
    .png, .tiff,
    NSPasteboard.PasteboardType(UTType.jpeg.identifier),
    NSPasteboard.PasteboardType(UTType.heic.identifier),
    NSPasteboard.PasteboardType(UTType.webP.identifier),
    NSPasteboard.PasteboardType(UTType.gif.identifier),
  ]

  private let pasteboard: AutomationPasteboardReading
  private let isOwnWrite: (Int) -> Bool
  private let isSnapzyFrontmost: () -> Bool
  private let isSnapzyFile: (URL) -> Bool
  /// Called with the change count of a new foreign image on the clipboard.
  private let onImageCopied: (Int) -> Void
  private var timer: Timer?
  private var lastChangeCount: Int

  init(
    pasteboard: AutomationPasteboardReading = NSPasteboard.general,
    isOwnWrite: @escaping (Int) -> Bool = { SnapzyPasteboardWrites.isOwned(changeCount: $0) },
    isSnapzyFrontmost: @escaping () -> Bool = {
      NSWorkspace.shared.frontmostApplication?.processIdentifier == ProcessInfo.processInfo.processIdentifier
    },
    isSnapzyFile: @escaping (URL) -> Bool = AutomationClipboardWatcher.isSnapzyTempFile,
    onImageCopied: @escaping (Int) -> Void
  ) {
    self.pasteboard = pasteboard
    self.isOwnWrite = isOwnWrite
    self.isSnapzyFrontmost = isSnapzyFrontmost
    self.isSnapzyFile = isSnapzyFile
    self.onImageCopied = onImageCopied
    lastChangeCount = pasteboard.changeCount
  }

  var isRunning: Bool { timer != nil }

  /// Starts polling. What is on the clipboard now never fires.
  func start(interval: TimeInterval = AutomationEventLimits.clipboardPollInterval) {
    guard timer == nil else { return }
    lastChangeCount = pasteboard.changeCount
    let timer = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
      MainActor.assumeIsolated { self?.poll() }
    }
    // Generous tolerance lets the system batch the wake-ups with others.
    timer.tolerance = interval * 0.5
    RunLoop.main.add(timer, forMode: .common)
    self.timer = timer
  }

  func stop() {
    timer?.invalidate()
    timer = nil
  }

  /// One tick. Internal for tests.
  func poll() {
    let count = pasteboard.changeCount
    guard count != lastChangeCount else { return }
    lastChangeCount = count
    guard shouldFire(changeCount: count) else { return }
    onImageCopied(count)
  }

  /// The clipboard changed: is it a foreign image worth running on?
  func shouldFire(changeCount: Int) -> Bool {
    if isOwnWrite(changeCount) || isSnapzyFrontmost() { return false }
    let types = Set(pasteboard.types ?? [])
    guard !types.isEmpty, types.isDisjoint(with: Self.privateTypes) else { return false }
    if types.contains(.fileURL) {
      // Finder copies: only image files count (a file's icon is not "an image").
      let images = pasteboard.fileURLs().filter { AutomationFileKind.of($0) == .image || AutomationFileKind.of($0) == .gif }
      return !images.isEmpty && !images.contains(where: isSnapzyFile)
    }
    return !types.isDisjoint(with: Self.imageDataTypes)
  }

  /// Files in Snapzy's temp capture folder (a pasted Snapzy capture copied again elsewhere).
  static func isSnapzyTempFile(_ url: URL) -> Bool {
    let temp = TempCaptureManager.shared.tempCaptureDirectory.standardizedFileURL.path
    return url.standardizedFileURL.path.hasPrefix(temp + "/")
      || AutomationFileOriginTracker.shared.wasWrittenBySnapzy(url)
  }
}
