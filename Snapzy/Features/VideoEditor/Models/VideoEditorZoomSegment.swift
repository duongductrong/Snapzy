import Foundation

/// Represents a zoom effect segment on the video timeline
nonisolated struct ZoomSegment: Identifiable, Codable, Equatable, Hashable {
  let id: UUID
  /// Seconds on the editor's structural timeline, independent of clip source time.
  var startTime: TimeInterval
  var duration: TimeInterval // zoom duration in seconds
  var zoomLevel: CGFloat // 1.0 (100%) to 4.0 (400%)
  var zoomCenter: CGPoint // normalized 0-1 for x,y position
  var zoomType: ZoomType
  var followSpeed: Double
  var focusMargin: CGFloat
  var isEnabled: Bool
  /// Optional action/outcome camera keyframes generated by Smart Auto-Zoom (source time).
  /// `nil` for manual zooms and standard live cursor-follow zooms.
  var smartKeyframes: [AutoFocusCameraSample]?

  // MARK: - Computed Properties

  var endTime: TimeInterval {
    startTime + duration
  }

  var isSmartAutoZoom: Bool {
    zoomType == .auto && (smartKeyframes?.isEmpty == false)
  }

  // MARK: - Constants

  static let defaultDuration: TimeInterval = 2.0
  static let defaultZoomLevel: CGFloat = 2.0
  static let minDuration: TimeInterval = 0.5
  static let maxDuration: TimeInterval = 30.0
  static let maxTimelineStart: TimeInterval = 864_000
  static let minZoomLevel: CGFloat = 1.0
  static let maxZoomLevel: CGFloat = 4.0

  private enum CodingKeys: String, CodingKey {
    case id, startTime, duration, zoomLevel, zoomCenter
    case zoomType, followSpeed, focusMargin, isEnabled, smartKeyframes
  }

  // MARK: - Initialization

  init(
    id: UUID = UUID(),
    startTime: TimeInterval,
    duration: TimeInterval = ZoomSegment.defaultDuration,
    zoomLevel: CGFloat = ZoomSegment.defaultZoomLevel,
    zoomCenter: CGPoint = CGPoint(x: 0.5, y: 0.5),
    zoomType: ZoomType = .manual,
    followSpeed: Double = AutoFocusSettings.defaultFollowSpeed,
    focusMargin: CGFloat = AutoFocusSettings.defaultFocusMargin,
    isEnabled: Bool = true,
    smartKeyframes: [AutoFocusCameraSample]? = nil
  ) {
    self.id = id
    let safeStart = startTime.isFinite ? startTime : 0
    self.startTime = min(max(0, safeStart), Self.maxTimelineStart)
    let safeDuration = duration.isFinite ? duration : Self.defaultDuration
    self.duration = max(Self.minDuration, min(safeDuration, Self.maxDuration))
    let safeZoom = zoomLevel.isFinite ? zoomLevel : Self.defaultZoomLevel
    self.zoomLevel = max(Self.minZoomLevel, min(safeZoom, Self.maxZoomLevel))
    let safeX = zoomCenter.x.isFinite ? zoomCenter.x : 0.5
    let safeY = zoomCenter.y.isFinite ? zoomCenter.y : 0.5
    self.zoomCenter = CGPoint(
      x: max(0, min(safeX, 1)),
      y: max(0, min(safeY, 1))
    )
    self.zoomType = zoomType
    let safeFollow = followSpeed.isFinite ? followSpeed : AutoFocusSettings.defaultFollowSpeed
    self.followSpeed = AutoFocusSettings.clampFollowSpeed(safeFollow)
    let safeMargin = focusMargin.isFinite ? focusMargin : AutoFocusSettings.defaultFocusMargin
    self.focusMargin = AutoFocusSettings.clampFocusMargin(safeMargin)
    self.isEnabled = isEnabled
    self.smartKeyframes = smartKeyframes?.isEmpty == true ? nil : smartKeyframes
  }

  init(from decoder: Decoder) throws {
    let c = try decoder.container(keyedBy: CodingKeys.self)
    let decodedId = try c.decodeIfPresent(UUID.self, forKey: .id) ?? UUID()
    let decodedStart = (try? c.decodeIfPresent(TimeInterval.self, forKey: .startTime)) ?? 0
    let decodedDuration = (try? c.decodeIfPresent(TimeInterval.self, forKey: .duration)) ?? Self.defaultDuration
    let decodedLevel = (try? c.decodeIfPresent(CGFloat.self, forKey: .zoomLevel)) ?? Self.defaultZoomLevel
    let decodedCenter = (try? c.decodeIfPresent(CGPoint.self, forKey: .zoomCenter)) ?? CGPoint(x: 0.5, y: 0.5)
    let decodedType = (try? c.decodeIfPresent(ZoomType.self, forKey: .zoomType)) ?? .manual
    let decodedFollow = (try? c.decodeIfPresent(Double.self, forKey: .followSpeed))
      ?? AutoFocusSettings.defaultFollowSpeed
    let decodedMargin = (try? c.decodeIfPresent(CGFloat.self, forKey: .focusMargin))
      ?? AutoFocusSettings.defaultFocusMargin
    let decodedEnabled = (try? c.decodeIfPresent(Bool.self, forKey: .isEnabled)) ?? true
    let decodedKeyframes = try? c.decodeIfPresent([AutoFocusCameraSample].self, forKey: .smartKeyframes)

    self.init(
      id: decodedId,
      startTime: decodedStart,
      duration: decodedDuration,
      zoomLevel: decodedLevel,
      zoomCenter: decodedCenter,
      zoomType: decodedType,
      followSpeed: decodedFollow,
      focusMargin: decodedMargin,
      isEnabled: decodedEnabled,
      smartKeyframes: decodedKeyframes
    )
  }

  // MARK: - Validation

  /// Check if a given time falls within this zoom segment
  func contains(time: TimeInterval) -> Bool {
    time >= startTime && time < endTime
  }

  /// Check if this segment overlaps with another
  func overlaps(with other: ZoomSegment) -> Bool {
    startTime < other.endTime && endTime > other.startTime
  }

  /// Clamp segment to video duration
  func clamped(to videoDuration: TimeInterval) -> ZoomSegment {
    var clamped = self
    clamped.startTime = max(0, min(startTime, videoDuration - Self.minDuration))
    clamped.duration = min(duration, videoDuration - clamped.startTime)
    return clamped
  }
}

// MARK: - Zoom Type

nonisolated enum ZoomType: String, Codable, CaseIterable, Equatable {
  case auto // follow recorded mouse path within the zoom item's range
  case manual // user-defined camera framing

  var displayName: String {
    switch self {
    case .auto: L10n.VideoEditor.auto
    case .manual: L10n.VideoEditor.manual
    }
  }

  var iconName: String {
    switch self {
    case .auto: "cursorarrow.click"
    case .manual: "hand.tap"
    }
  }
}

// MARK: - Zoom Segment Extensions

nonisolated extension ZoomSegment {
  var autoFocusSettings: AutoFocusSettings {
    AutoFocusSettings(
      isEnabled: zoomType == .auto,
      zoomLevel: zoomLevel,
      followSpeed: followSpeed,
      focusMargin: focusMargin
    )
  }

  var isAutoMode: Bool {
    zoomType == .auto
  }

  /// Create a zoom segment centered at a specific time
  static func centered(
    at time: TimeInterval,
    duration: TimeInterval = defaultDuration,
    zoomLevel: CGFloat = defaultZoomLevel,
    center: CGPoint = CGPoint(x: 0.5, y: 0.5),
    type: ZoomType = .manual
  ) -> ZoomSegment {
    ZoomSegment(
      startTime: max(0, time - duration / 2),
      duration: duration,
      zoomLevel: zoomLevel,
      zoomCenter: center,
      zoomType: type
    )
  }

  /// Formatted zoom level string (e.g., "2x", "1.5x")
  var formattedZoomLevel: String {
    if zoomLevel == floor(zoomLevel) {
      String(format: "%.0fx", zoomLevel)
    } else {
      String(format: "%.1fx", zoomLevel)
    }
  }

  /// Formatted duration string
  var formattedDuration: String {
    if duration < 1 {
      String(format: "%.1fs", duration)
    } else if duration == floor(duration) {
      String(format: "%.0fs", duration)
    } else {
      String(format: "%.1fs", duration)
    }
  }
}
